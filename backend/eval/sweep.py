#!/usr/bin/env python3
"""
Fit the attention thresholds against per-frame ground-truth labels.

    python eval/sweep.py eval/out/lesson1.jsonl annotations/lesson1.csv \
        --out eval/configs/tuned.yaml

Replays the extract cache through every candidate threshold set and keeps the
one with the best binary F1 (attentive vs off-task) from eval/metrics.Scorer —
the same headline number run_eval.py reports.

This is the finer of the two fitters. tune_from_feedback.py is the coarse
teacher-rating version; they share the search grid in eval/tuning.py.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from app.config import settings                                   # noqa: E402
from app.pipeline.engagement_engine import AttentionConfig        # noqa: E402
from eval.run_eval import Record, score_records                   # noqa: E402
from eval.tuning import TUNED_FIELDS, candidate_configs           # noqa: E402


def _f1(report: dict) -> float:
    value = report.get("overall", {}).get("binary_f1")
    return value if value is not None else -1.0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("jsonl", help="extract cache from run_eval.py")
    parser.add_argument("annotations", help="ground-truth annotations.csv (kept for provenance)")
    parser.add_argument("--calibrate", choices=("video-start", "oracle"), default="video-start")
    parser.add_argument("--out", help="write the winning fields here as YAML")
    parser.add_argument("--report", help="write the full before/after JSON here")
    args = parser.parse_args()

    records = [Record.from_json(line) for line in open(args.jsonl, encoding="utf-8")]
    if not records:
        raise SystemExit(f"empty cache: {args.jsonl}")

    base = AttentionConfig.from_settings(settings)
    base_report = score_records(records, base, args.calibrate, base.calibration_seconds)
    base_f1 = _f1(base_report)

    best_config, best_report, best_f1 = base, base_report, base_f1
    considered = 1
    for candidate in candidate_configs(base):
        considered += 1
        report = score_records(records, candidate, args.calibrate, candidate.calibration_seconds)
        f1 = _f1(report)
        if f1 > best_f1:
            best_config, best_report, best_f1 = candidate, report, f1

    overrides = {f: getattr(best_config, f) for f in TUNED_FIELDS}
    summary = {
        "considered_configs": considered,
        "calibration": args.calibrate,
        "annotations": args.annotations,
        "baseline": {
            "binary_f1": base_report["overall"].get("binary_f1"),
            "accuracy": base_report["overall"].get("accuracy"),
        },
        "tuned": {
            "binary_f1": best_report["overall"].get("binary_f1"),
            "accuracy": best_report["overall"].get("accuracy"),
        },
        "overrides": overrides,
        "unchanged": best_config == base,
    }

    print(json.dumps(summary, indent=2))
    if summary["unchanged"]:
        print("\n[sweep] no grid config beat the baseline F1 — thresholds left as they are")

    if args.out:
        import yaml
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write("# Generated by eval/sweep.py — per-frame ground-truth labels.\n")
            fh.write(f"# baseline binary_f1 {base_f1:.4f} -> tuned {best_f1:.4f}\n")
            yaml.safe_dump(overrides, fh, sort_keys=True)
        print(f"[sweep] overrides -> {args.out}")
    if args.report:
        os.makedirs(os.path.dirname(args.report) or ".", exist_ok=True)
        with open(args.report, "w", encoding="utf-8") as fh:
            json.dump({**summary, "baseline_full": base_report, "tuned_full": best_report}, fh, indent=2)
        print(f"[sweep] report -> {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
